from sqlalchemy import (
    Boolean, Column, DateTime, Float, ForeignKey, Index, Integer, String, Text, UniqueConstraint, func,
)

from app.models.base import Base


class ThunderOutreachVariant(Base):
    """Approved copy for one cadence step. Copy is seeded by db_contract and
    never generated by an LLM, so nothing unapproved reaches a candidate."""
    __tablename__ = "thunder_outreach_variants"
    __table_args__ = (Index("ix_thunder_variant_step_active", "step", "active"),)

    id = Column(Integer, primary_key=True)
    key = Column(String(64), nullable=False, unique=True)
    step = Column(String(16), nullable=False)  # "1".."4", NURTURE, ACK_*
    subject_template = Column(String(512), nullable=False)
    body_template = Column(Text, nullable=False)
    requires_job = Column(Boolean, nullable=False, default=False)
    active = Column(Boolean, nullable=False, default=True)
    retired_reason = Column(String(512), nullable=True)
    created_at = Column(DateTime, server_default=func.now())


class ThunderEmailMessage(Base):
    __tablename__ = "thunder_email_messages"
    __table_args__ = (
        UniqueConstraint("mailbox", "internet_message_id", name="uq_thunder_email_internet_id"),
        UniqueConstraint("candidate_id", "cadence_seq", "step", "direction", name="uq_thunder_email_step"),
        Index("ix_thunder_email_variant", "variant_id", "direction", "status"),
    )

    id = Column(String(36), primary_key=True)
    tenant_id = Column(Integer, nullable=True, index=True)
    candidate_id = Column(String(512), ForeignKey("candidates.candidateID"), nullable=False, index=True)
    direction = Column(String(3), nullable=False)  # OUT / IN
    # OUT: QUEUED -> DRAFTED -> SENT | SUPERSEDED ; IN: RECEIVED -> PROCESSED | IGNORED
    status = Column(String(16), nullable=False)
    cadence_seq = Column(Integer, nullable=False, default=1)
    step = Column(String(16), nullable=True)  # NULL on IN rows (NULLs never collide in the unique key)
    variant_id = Column(Integer, ForeignKey("thunder_outreach_variants.id"), nullable=True)
    mailbox = Column(String(320), nullable=False)
    graph_message_id = Column(String(512), nullable=True)
    conversation_id = Column(String(512), nullable=True, index=True)
    internet_message_id = Column(String(998), nullable=True)
    in_reply_to = Column(String(998), nullable=True)
    from_address = Column(String(320), nullable=True)
    subject = Column(String(998), nullable=True)
    body_text = Column(Text, nullable=True)
    intent = Column(String(32), nullable=True)
    intent_confidence = Column(Float, nullable=True)
    intent_source = Column(String(16), nullable=True)  # rule / llm / keyword
    credited_out_id = Column(String(36), ForeignKey("thunder_email_messages.id"), nullable=True)
    not_sent_reason = Column(String(512), nullable=True)
    created_at = Column(DateTime, server_default=func.now())
    sent_at = Column(DateTime, nullable=True)
    received_at = Column(DateTime, nullable=True)
    processed_at = Column(DateTime, nullable=True)


class ThunderCadenceState(Base):
    """One row per candidate in Thunder's email cadence. next_action_at is the
    single schedule: changing it is how future touches are cancelled. Silence
    never ends the cadence (no terminal state for silence); only opt-out or a
    hostile reply moves a candidate to STOPPED."""
    __tablename__ = "thunder_cadence_state"

    candidate_id = Column(String(512), ForeignKey("candidates.candidateID"), primary_key=True)
    tenant_id = Column(Integer, nullable=True, index=True)
    job_id = Column(String(512), nullable=True)
    cadence_seq = Column(Integer, nullable=False, default=1)
    stage = Column(String(16), nullable=False, default="ACTIVE")  # ACTIVE / NURTURE / HANDOFF / STOPPED
    next_step = Column(String(16), nullable=True)
    next_action_at = Column(DateTime, nullable=True, index=True)
    touches_sent = Column(Integer, nullable=False, default=0)
    last_outbound_at = Column(DateTime, nullable=True)
    last_inbound_at = Column(DateTime, nullable=True)
    stop_reason = Column(String(255), nullable=True)
    updated_at = Column(DateTime, server_default=func.now(), onupdate=func.now())


class ThunderMailboxCursor(Base):
    __tablename__ = "thunder_mailbox_cursor"

    mailbox = Column(String(320), primary_key=True)
    last_received_at = Column(DateTime, nullable=True)
    last_run_at = Column(DateTime, nullable=True)
    last_error = Column(Text, nullable=True)


class ThunderMonthlyHighlight(Base):
    """Admin-authored monthly highlight for the nurture email. No row for a
    month means the nurture email carries only real matching open jobs."""
    __tablename__ = "thunder_monthly_highlights"
    __table_args__ = (UniqueConstraint("tenant_id", "month", name="uq_thunder_highlight_month"),)

    id = Column(Integer, primary_key=True)
    tenant_id = Column(Integer, nullable=False)
    month = Column(String(7), nullable=False)  # YYYY-MM
    title = Column(String(255), nullable=False)
    body_html = Column(Text, nullable=False)
    approved_by = Column(String(255), nullable=True)
    created_at = Column(DateTime, server_default=func.now())
